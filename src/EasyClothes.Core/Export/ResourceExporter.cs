using System.Globalization;
using System.Text;
using System.Text.Json;
using System.Xml;
using System.Xml.Linq;
using EasyClothes.Core.Model;
using EasyClothes.Core.Rage;
using EasyClothes.Core.Textures;
using EasyClothes.Core.Validation;

namespace EasyClothes.Core.Export;

public sealed record ExportResult(string OutputDir, int Drawables, int Tattoos, int Files, IReadOnlyList<string> Warnings);

public sealed class ExportException(IReadOnlyList<string> errors)
    : Exception("El proyecto tiene errores:\n" + string.Join("\n", errors))
{
    public IReadOnlyList<string> Errors { get; } = errors;
}

// Builds a ready-to-run FiveM resource: fxmanifest.lua, the shop .meta per ped and
// a stream folder with the .ymt and every model/texture renamed to the game's scheme.
public static class ResourceExporter
{
    public const string Marker = "-- Generated by EasyClothes";
    public const int MaxTattooSide = 1024;

    public static ExportResult Export(ClothingProject project, string projectDir, string outputDir)
    {
        var errors = ProjectValidator.Validate(project, projectDir).Where(i => i.Severity == IssueSeverity.Error).Select(i => i.Message).ToList();
        if (errors.Count > 0) throw new ExportException(errors);
        EnsureReplaceable(outputDir);

        var staging = Path.Combine(Path.GetDirectoryName(Path.GetFullPath(outputDir))!, $".{Path.GetFileName(outputDir)}.{Guid.NewGuid():N}.tmp");
        try
        {
            var result = WriteResource(project, projectDir, staging);
            if (Directory.Exists(outputDir)) Directory.Delete(outputDir, recursive: true);
            Directory.Move(staging, outputDir);
            return result with { OutputDir = outputDir };
        }
        finally
        {
            if (Directory.Exists(staging)) Directory.Delete(staging, recursive: true);
        }
    }

    private static ExportResult WriteResource(ClothingProject project, string projectDir, string dir)
    {
        var collection = project.CollectionName;
        var warnings = new List<string>();
        var files = 0;
        var dataFiles = new List<(string Type, string File)>();
        var stream = Directory.CreateDirectory(Path.Combine(dir, "stream")).FullName;

        foreach (var gender in Enum.GetValues<PedGender>())
        {
            var drawables = project.DrawablesFor(gender).ToList();
            if (drawables.Count == 0) continue;
            var ped = PedSlotNames.PedModel(gender);
            var pedStream = Directory.CreateDirectory(Path.Combine(stream, ped)).FullName;

            var components = new Dictionary<ComponentSlot, IReadOnlyList<int>>();
            foreach (var slot in drawables.Where(d => d.Component is not null).GroupBy(d => d.Component!.Value))
            {
                var ordered = ClothingProject.InGameOrder(slot);
                var code = PedSlotNames.FileCode(slot.Key);
                for (var i = 0; i < ordered.Count; i++)
                {
                    var prefix = $"{ped}_{collection}^{code}";
                    files += Copy(projectDir, ordered[i].ModelPath, pedStream, $"{prefix}_{i:000}_u.ydd");
                    for (var t = 0; t < ordered[i].Textures.Count; t++)
                        files += Copy(projectDir, ordered[i].Textures[t].TexturePath, pedStream, $"{prefix}_diff_{i:000}_{TextureVariation.LetterFor(t)}_uni.ytd");
                    WarnFirstPerson(warnings, ordered[i]);
                }
                components[slot.Key] = ordered.Select(d => d.Textures.Count).ToList();
            }

            var props = new Dictionary<PropSlot, IReadOnlyList<int>>();
            foreach (var slot in drawables.Where(d => d.Prop is not null).GroupBy(d => d.Prop!.Value))
            {
                var ordered = ClothingProject.InGameOrder(slot);
                var prefix = $"{ped}_p_{collection}^{PedSlotNames.FileCode(slot.Key)}";
                for (var i = 0; i < ordered.Count; i++)
                {
                    files += Copy(projectDir, ordered[i].ModelPath, pedStream, $"{prefix}_{i:000}.ydd");
                    for (var t = 0; t < ordered[i].Textures.Count; t++)
                        files += Copy(projectDir, ordered[i].Textures[t].TexturePath, pedStream, $"{prefix}_diff_{i:000}_{TextureVariation.LetterFor(t)}.ytd");
                    WarnFirstPerson(warnings, ordered[i]);
                }
                props[slot.Key] = ordered.Select(d => d.Textures.Count).ToList();
            }

            PedVariation.Write(collection, components, props).Write(Path.Combine(stream, $"{ped}_{collection}.ymt"));
            var shopMeta = $"{ped}_{collection}.meta";
            SaveXml(ShopMeta(ped, collection), Path.Combine(dir, shopMeta));
            dataFiles.Add(("SHOP_PED_APPAREL_META_FILE", shopMeta));
            files += 2;
        }

        if (project.Tattoos.Count > 0)
        {
            var overlays = $"{collection}_overlays.xml";
            files += WriteTattoos(project, projectDir, dir, Directory.CreateDirectory(Path.Combine(stream, "tattoos")).FullName, overlays);
            dataFiles.Add(("PED_OVERLAY_FILE", overlays));
        }

        File.WriteAllText(Path.Combine(dir, "fxmanifest.lua"), Manifest(project, dataFiles), new UTF8Encoding(false));
        return new ExportResult(dir, project.Drawables.Count, project.Tattoos.Count, files + 1, warnings);
    }

    // One .ytd per tattoo plus the overlay collection; scripts apply them with
    // AddPedDecorationFromHashes(ped, "<collection>_overlays", "<collection>_tat_000_M").
    private static int WriteTattoos(ClothingProject project, string projectDir, string dir, string tattooStream, string overlaysFile)
    {
        var collection = project.CollectionName;
        var items = new XElement("presetOverlays");
        var list = new List<object>();
        var tattoos = project.Tattoos.OrderBy(t => t.Name, StringComparer.OrdinalIgnoreCase).ThenBy(t => t.Id).ToList();
        for (var i = 0; i < tattoos.Count; i++)
        {
            var tattoo = tattoos[i];
            var txd = $"{collection}_tat_{i:000}";
            var image = ImageLoader.Load(Path.Combine(projectDir, tattoo.TexturePath));
            var (width, height) = TextureOptimizer.TargetSize(image.Width, image.Height, MaxTattooSide);
            if ((width, height) != (image.Width, image.Height)) image = ImageResampler.Resize(image, width, height);
            TextureDictionaryWriter.Create([(txd, TextureEncoder.Encode(image, TextureFormat.Dxt5))]).Write(Path.Combine(tattooStream, txd + ".ytd"));

            var overlays = new Dictionary<string, string>();
            foreach (var gender in tattoo.Genders.Distinct().Order())
            {
                var overlay = $"{txd}_{(gender == PedGender.Male ? "M" : "F")}";
                overlays[gender.ToString().ToLowerInvariant()] = overlay;
                items.Add(new XElement("Item",
                    new XElement("uvPos", new XAttribute("x", Number(tattoo.UvX)), new XAttribute("y", Number(tattoo.UvY))),
                    new XElement("scale", new XAttribute("x", Number(tattoo.ScaleX)), new XAttribute("y", Number(tattoo.ScaleY))),
                    new XElement("rotation", new XAttribute("value", Number(tattoo.Rotation))),
                    new XElement("nameHash", overlay),
                    new XElement("txdHash", txd),
                    new XElement("txtHash", txd),
                    new XElement("zone", ZoneName(tattoo.Zone)),
                    new XElement("type", "TYPE_TATTOO"),
                    new XElement("faction", "FM"),
                    new XElement("garment", "All"),
                    new XElement("gender", gender == PedGender.Male ? "GENDER_MALE" : "GENDER_FEMALE"),
                    new XElement("award"),
                    new XElement("awardLevel")));
            }
            list.Add(new { name = tattoo.Name, zone = ZoneName(tattoo.Zone), collection = Path.GetFileNameWithoutExtension(overlaysFile), overlays });
        }

        SaveXml(new XDocument(new XDeclaration("1.0", "UTF-8", null),
            new XElement("PedDecorationCollection",
                new XElement("bRequiredForSync", new XAttribute("value", "true")),
                new XElement("medalLocations"),
                new XElement("medals"),
                items)), Path.Combine(dir, overlaysFile));
        File.WriteAllText(Path.Combine(dir, "tattoos.json"), JsonSerializer.Serialize(list, new JsonSerializerOptions { WriteIndented = true }), new UTF8Encoding(false));
        return tattoos.Count + 2;
    }

    private static string Number(float value) => value.ToString("0.000000", CultureInfo.InvariantCulture);

    private static string ZoneName(TattooZone zone) => zone switch
    {
        TattooZone.Torso => "ZONE_TORSO",
        TattooZone.Head => "ZONE_HEAD",
        TattooZone.LeftArm => "ZONE_LEFT_ARM",
        TattooZone.RightArm => "ZONE_RIGHT_ARM",
        TattooZone.LeftLeg => "ZONE_LEFT_LEG",
        TattooZone.RightLeg => "ZONE_RIGHT_LEG",
        _ => throw new ArgumentOutOfRangeException(nameof(zone), zone, null),
    };

    private static int Copy(string projectDir, string relative, string targetDir, string name)
    {
        File.Copy(Path.Combine(projectDir, relative), Path.Combine(targetDir, name));
        return 1;
    }

    private static void WarnFirstPerson(List<string> warnings, Drawable d)
    {
        if (d.FirstPersonModelPath is not null)
            warnings.Add($"{d.Name}: el modelo de primera persona todavía no se exporta.");
    }

    // No BOM: the game's XML parser expects the declaration as the very first bytes.
    private static void SaveXml(XDocument document, string path)
    {
        using var writer = XmlWriter.Create(path, new XmlWriterSettings { Encoding = new UTF8Encoding(false), Indent = true });
        document.Save(writer);
    }

    private static XDocument ShopMeta(string ped, string collection) => new(
        new XDeclaration("1.0", "UTF-8", null),
        new XElement("ShopPedApparel",
            new XElement("pedName", ped),
            new XElement("dlcName", collection),
            new XElement("fullDlcName", $"{ped}_{collection}"),
            new XElement("eCharacter", "SCR_CHAR_MULTIPLAYER"),
            new XElement("pedOutfits"),
            new XElement("pedComponents"),
            new XElement("pedProps")));

    private static string Manifest(ClothingProject project, IReadOnlyList<(string Type, string File)> dataFiles)
    {
        var sb = new StringBuilder();
        sb.AppendLine(Marker);
        sb.AppendLine("fx_version 'cerulean'");
        sb.AppendLine("game 'gta5'");
        sb.AppendLine();
        sb.AppendLine($"name '{Lua(project.Name)}'");
        if (project.Author is { Length: > 0 } author) sb.AppendLine($"author '{Lua(author)}'");
        if (project.Description is { Length: > 0 } description) sb.AppendLine($"description '{Lua(description)}'");
        sb.AppendLine();
        sb.AppendLine("files {");
        foreach (var (_, file) in dataFiles) sb.AppendLine($"  '{file}',");
        sb.AppendLine("}");
        sb.AppendLine();
        foreach (var (type, file) in dataFiles) sb.AppendLine($"data_file '{type}' '{file}'");
        return sb.ToString();
    }

    private static string Lua(string text) => text.Replace("\\", "\\\\").Replace("'", "\\'").ReplaceLineEndings(" ");

    // Only overwrite folders that are empty or were generated by us.
    private static void EnsureReplaceable(string outputDir)
    {
        if (!Directory.Exists(outputDir) || !Directory.EnumerateFileSystemEntries(outputDir).Any()) return;
        var manifest = Path.Combine(outputDir, "fxmanifest.lua");
        var ours = File.Exists(manifest) && (File.ReadLines(manifest).FirstOrDefault()?.StartsWith(Marker) ?? false);
        if (!ours)
            throw new IOException($"La carpeta {outputDir} ya existe y no la generó EasyClothes; elige otra o vacíala.");
    }
}
